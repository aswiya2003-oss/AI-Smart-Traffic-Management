from io import BytesIO
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet

def create_pdf_report(result):
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4)
    styles = getSampleStyleSheet()
    story = [
        Paragraph("AI Smart Traffic Management System", styles["Title"]),
        Spacer(1, 12),
        Paragraph("Traffic Video Analysis Report", styles["Heading2"]),
        Spacer(1, 8),
        Paragraph(f"Model: {result['model']}", styles["BodyText"]),
        Paragraph(f"Frames processed: {result['frames_processed']}", styles["BodyText"]),
        Paragraph(f"Peak vehicle count in a frame: {result['peak_count']}", styles["BodyText"]),
        Paragraph(f"Traffic density: {result['density']}", styles["BodyText"]),
        Paragraph(f"Simulated green-time recommendation: {result['green_seconds']} seconds", styles["BodyText"]),
        Spacer(1, 16),
        Paragraph("This report is generated by an academic prototype. The signal timing is not an instruction "
                  "to operate real traffic-control equipment.", styles["Italic"]),
        Spacer(1, 12),
    ]
    rows = [["Time (seconds)", "Vehicle count", "Density", "Suggested green (s)"]]
    for item in result["timeline"][:30]:
        rows.append([str(item["time_seconds"]), str(item["vehicle_count"]),
                     item["density"], str(item["suggested_green_seconds"])])
    table = Table(rows, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#243b53")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(table)
    doc.build(story)
    return buffer.getvalue()
